from __future__ import annotations

from pathlib import Path

import pytest


def pytest_runtest_makereport(item: pytest.Item, call: pytest.CallInfo[object]):
    report = pytest.TestReport.from_item_and_call(item, call)
    setattr(item, f"rep_{report.when}", report)
    return report


def pytest_sessionfinish(session: pytest.Session, exitstatus: int) -> None:
    rows = []
    for item in session.items:
        reports = [
            getattr(item, stage, None)
            for stage in ("rep_setup", "rep_call", "rep_teardown")
        ]
        reports = [report for report in reports if report is not None]
        failed = next((report for report in reports if report.failed), None)
        skipped = next((report for report in reports if report.skipped), None)
        if failed:
            status = "FAIL"
            actual = str(failed.longreprtext).strip()
        elif skipped:
            status = "SKIP"
            actual = f"Skipped: {skipped.longreprtext}"
        else:
            status = "PASS"
            actual = "Assertions completed successfully."

        marker = item.get_closest_marker("case")
        metadata = marker.kwargs if marker else {}
        case_id = metadata.get("id", item.nodeid)
        if hasattr(item, "callspec"):
            case_id = f"{case_id}-{item.callspec.id}"
        rows.append(
            {
                "id": case_id,
                "name": metadata.get("name", item.name),
                "inputs": metadata.get(
                    "inputs", "Existing regression test; see the test node ID."
                ),
                "expected": metadata.get(
                    "expected", "All assertions defined by this test pass."
                ),
                "actual": actual,
                "status": status,
                "nodeid": item.nodeid,
            }
        )

    passed = sum(row["status"] == "PASS" for row in rows)
    failed_rows = [row for row in rows if row["status"] == "FAIL"]
    skipped = sum(row["status"] == "SKIP" for row in rows)
    overall = "PASS" if exitstatus == 0 and not failed_rows else "FAIL"

    lines = [
        "# Reverse Logistics Automated Test Report",
        "",
        "Generated by the pytest session that executed this report. Actual results and statuses are recorded from pytest outcomes.",
        "",
        "## Summary",
        "",
        "| Metric | Result |",
        "|---|---:|",
        f"| Total test cases | {len(rows)} |",
        f"| Passed tests | {passed} |",
        f"| Failed tests | {len(failed_rows)} |",
        f"| Skipped tests | {skipped} |",
        f"| Overall test status | **{overall}** |",
        "",
        "## Test case results",
        "",
        "| Test ID | Test Name | Input Conditions | Expected Result | Actual Result | Status |",
        "|---|---|---|---|---|---|",
    ]
    for row in rows:
        cells = [
            row["id"],
            row["name"],
            row["inputs"],
            row["expected"],
            row["actual"].replace("\n", "<br>"),
            row["status"],
        ]
        lines.append("| " + " | ".join(str(cell).replace("|", "\\|") for cell in cells) + " |")

    lines.extend(["", "## Failed tests", ""])
    if failed_rows:
        for row in failed_rows:
            lines.extend(
                [
                    f"### {row['name']} (`{row['nodeid']}`)",
                    "",
                    row["actual"],
                    "",
                ]
            )
    else:
        lines.append("No tests failed.")
    lines.append("")

    report_path = Path(__file__).parent / "test_report.md"
    report_path.write_text("\n".join(lines), encoding="utf-8")
